console.log('This site was generated by Hugo.');

document.documentElement.classList.add('js');

document.addEventListener('DOMContentLoaded', () => {
  const profiles = document.querySelectorAll('.profile-options .profile-figure');
  const quotes = document.querySelectorAll('.profile-quotes blockquote');

  if (profiles.length > 0) {
    const randomIndex = Math.floor(Math.random() * profiles.length);
    const selectedProfile = profiles[randomIndex];
    const image = selectedProfile.querySelector('.profile-photo');

    if (image) {
      image.src = image.dataset.src;
    }

    selectedProfile.classList.add('is-selected');
  }

  if (quotes.length > 0) {
    const randomIndex = Math.floor(Math.random() * quotes.length);
    quotes[randomIndex].classList.add('is-selected');
  }
}, { once: true });
